        Product::query()->chunkById(1000, function ($products) use (&$buffer, $bufferSize, $imagePool) {
            foreach ($products as $product) {
                $nImages = rand(1, 3);
                $shuffled = $imagePool;
                shuffle($shuffled);

                // prendre nImages premières d'un ordre aléatoire
                for ($i = 0; $i < $nImages; $i++) {
                    $path = $shuffled[$i % count($shuffled)];
                    $buffer[] = [
                        'product_id' => $product->id,
                        'path' => $path,
                        'alt' => $product->name . ' - image ' . ($i + 1),
                        'is_primary' => ($i === 0) ? true : false,
                        'position' => $i + 1,
                        'created_at' => now(),
                        'updated_at' => now(),
                    ];

                    if (count($buffer) >= $bufferSize) {
                        DB::table('product_images')->insert($buffer);
                        $buffer = [];
                    }
                }
            }
        });

        if (count($buffer) > 0) {
            DB::table('product_images')->insert($buffer);
            $buffer = [];
